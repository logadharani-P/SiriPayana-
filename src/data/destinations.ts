export const getDestinationBySlug = (slug: string): Destination | undefined =>
  destinations.find(d => d.slug === slug);

export const getDestinationsByRegion = (region: Region): Destination[] =>
  destinations.filter(d => d.region === region);

export const getDestinationsByCategory = (category: DestinationCategory): Destination[] =>
  destinations.filter(d => d.category === category);

export const searchDestinations = (query: string): Destination[] => {
  const lower = query.toLowerCase();
  return destinations.filter(d =>
    d.name.toLowerCase().includes(lower) ||
    d.district.toLowerCase().includes(lower) ||
    d.shortDescription.toLowerCase().includes(lower) ||
    d.category.toLowerCase().includes(lower)
  );
};

